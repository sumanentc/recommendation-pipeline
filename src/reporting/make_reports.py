"""Stage 8 - Reporting: architecture diagram, report draft, README results block."""
from __future__ import annotations

import time
from pathlib import Path

from src.common.config import data_dir
from src.common.io import read_json, utc_now_iso
from src.common.log import get_logger
from src.reporting.diagram import draw_architecture
from src.reporting import final_report

log = get_logger("reporting")

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def update_readme(cfg: dict) -> bool:
    readme = Path(cfg["_root"]) / "README.md"
    if not readme.exists():
        return False
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        return False
    rep = data_dir(cfg, "reports")
    res = read_json(rep / "model_comparison.json")
    val = read_json(rep / "validation_report.json")
    k = res["primary_k"]
    lines = [f"_Auto-generated by the pipeline (stage `report`) on {utc_now_iso()}_", "",
             f"**Evaluation (K={k}, time-based test set)**", "",
             f"| Model | Precision@{k} | Recall@{k} | NDCG@{k} | Coverage@{k} | Diversity@{k} | RMSE | MAE |",
             "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for r in res["results"]:
        lines.append(f"| {r['model']} | {r[f'precision_at_{k}']:.4f} | {r[f'recall_at_{k}']:.4f} | {r[f'ndcg_at_{k}']:.4f} | "
                     f"{r[f'coverage_at_{k}']:.3f} | {r[f'diversity_at_{k}']:.3f} | {r['rmse']:.3f} | {r['mae']:.3f} |")
    t = val["tables"]["interactions"]
    lines += ["", f"**Validation:** {t['rows_in']:,} interaction rows in -> {t['rows_valid']:,} valid, {t['rows_rejected']:,} rejected "
              f"({t['reject_rate_pct']}%) - see `reports/validation_report.md`."]
    new = text[: text.index(START) + len(START)] + "\n" + "\n".join(lines) + "\n" + text[text.index(END):]
    readme.write_text(new, encoding="utf-8")
    return True


def run(cfg: dict) -> dict:
    t0 = time.time()
    docs = data_dir(cfg, "docs")
    draw_architecture(docs / "architecture.png")
    out = final_report.run(cfg)
    readme_updated = update_readme(cfg)
    log.info("Wrote docs/architecture.png, reports/final_report_draft.{md,html}; README updated=%s", readme_updated)
    return {"stage": "report", "finished_at": utc_now_iso(), **out, "readme_updated": readme_updated,
            "seconds": round(time.time() - t0, 2)}
